const WEEKDAYS = {
  en: ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'],
  bn: ['রবি', 'সোম', 'মঙ্গল', 'বুধ', 'বৃহ', 'শুক্র', 'শনি'],
};

export const LANGUAGES = Object.keys(STRINGS);
/** Bangla is the default: patients are Bangla speakers. A visitor's own choice, once made, wins. */
export const DEFAULT_LANG = 'bn';

/** Falls back to English, then to the key, so a missing string never shows as "undefined". */
export const t = (lang, key) => STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;

/**
 * Days in Bangladesh week order (Saturday first). Three or more days in a row become a range:
 * [6,0,1,2,3,4] -> "Sat–Thu", [0,2,4] -> "Sun, Tue, Thu".
 */
export function daysLabel(days, lang) {
  const names = WEEKDAYS[lang] ?? WEEKDAYS.en;
  const order = [6, 0, 1, 2, 3, 4, 5].filter((d) => days.includes(d));
  const runs = [];
  for (const d of order) {
    const last = runs.at(-1);
    if (last && (last.at(-1) + 1) % 7 === d) last.push(d);
    else runs.push([d]);
  }
  return runs.flatMap((run) => (run.length >= 3 ? [`${names[run[0]]}–${names[run.at(-1)]}`] : run.map((d) => names[d]))).join(', ');
}
